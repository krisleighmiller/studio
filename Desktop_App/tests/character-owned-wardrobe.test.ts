import { readFileSync } from "node:fs";
import { afterEach, expect, it, vi } from "vitest";
import * as desk from "../src/workflowDesk";
import { renderCharactersStage } from "../src/studio/surfaces/charactersStage";
import { resetSurfaceSession } from "../src/studio/surfaces/session";
import type { WorkflowImportResult } from "../src/workflowTypes";
const host = vi.hoisted(() => ({ invoke: vi.fn(), openDialog: vi.fn(), ask: vi.fn(), toMediaUrlAsync: vi.fn(async () => "data:image/png;base64,") }));
vi.mock("../src/host", () => host);
afterEach(() => { desk.clearWorkflowDesk(); resetSurfaceSession(); vi.clearAllMocks(); document.body.replaceChildren(); });
it("prepares an outfit for a saved character with no scene or references", async () => {
  const f = JSON.parse(readFileSync("tests/fixtures/sc05-import-result.json", "utf8")) as WorkflowImportResult;
  f.state.characters = [{id:"alice", name:"Alice", dir:"Characters/Alice", identity_ready:false, voice_ready:false, profile:{}}];
  f.state.scenes = []; f.state.assets = [];
  host.invoke.mockImplementation(async () => structuredClone(f));
  const unused = vi.fn(); const root = document.createElement("main"); document.body.append(root);
  desk.bindWorkflowDesk({root, projectRoot: () => "/fixture/project", onOpenPath: unused, onAddToChat: unused, onOpenVoice: unused, onComposeChat: unused, onSelectionChange: unused, chatModel: () => null, onStatus: unused, onPendingPlan: unused});
  await desk.loadWorkflowDesk("/fixture/project");
  const card = renderCharactersStage(intent => { void desk.handleCharacterIntent(intent); });
  const section = card.querySelector<HTMLElement>("[data-wardrobe-character]")!;
  const prompt = section.querySelector<HTMLTextAreaElement>('textarea[aria-label="Wardrobe description"]');
  expect(prompt).not.toBeNull();
  prompt!.value = "Red wool coat"; prompt!.dispatchEvent(new Event("input"));
  [...section.querySelectorAll("button")].find(b => b.textContent === "Generate wardrobe image")!.click();
  await vi.waitFor(() => expect(host.invoke).toHaveBeenCalledWith("workflow_generate_character_wardrobe", {projectRoot:"/fixture/project", characterId:"alice", prompt:"Red wool coat", referenceAssetIds:[]}));
});

it("routes ordered references and attaches an image for the character", async () => {
  const f = JSON.parse(readFileSync("tests/fixtures/sc05-import-result.json", "utf8")) as WorkflowImportResult;
  f.state.characters = [{id:"alice", name:"Alice", dir:"Characters/Alice", identity_ready:false, voice_ready:false, profile:{}}];
  f.state.scenes = [];
  f.state.assets = [{id:"one", path:"one.png", role:"identity_reference"}, {id:"two", path:"two.png", role:"identity_reference"}, {id:"outfit", path:"coat.png", role:"wardrobe_reference", character_id:"alice"}];
  host.invoke.mockImplementation(async () => structuredClone(f));
  host.openDialog.mockResolvedValue("/outside/coat.png");
  const unused = vi.fn(); const root = document.createElement("main"); document.body.append(root);
  desk.bindWorkflowDesk({root, projectRoot: () => "/fixture/project", onOpenPath: unused, onAddToChat: unused, onOpenVoice: unused, onComposeChat: unused, onSelectionChange: unused, chatModel: () => null, onStatus: unused, onPendingPlan: unused});
  await desk.loadWorkflowDesk("/fixture/project");
  let section = renderCharactersStage(intent => { void desk.handleCharacterIntent(intent); }).querySelector<HTMLElement>("[data-wardrobe-character]")!;
  expect(section.querySelector("figure")?.textContent).toContain("coat.png");
  const select = section.querySelector<HTMLSelectElement>('select[aria-label="Reference image"]')!;
  const add = section.querySelector<HTMLButtonElement>('[data-add-reference]')!;
  select.value = "two"; add.click(); select.value = "one"; add.click();
  section.querySelector<HTMLTextAreaElement>('textarea[aria-label="Wardrobe description"]')!.value = "Blue coat";
  [...section.querySelectorAll("button")].find(b => b.textContent === "Generate wardrobe image")!.click();
  await vi.waitFor(() => expect(host.invoke).toHaveBeenCalledWith("workflow_generate_character_wardrobe", {projectRoot:"/fixture/project", characterId:"alice", prompt:"Blue coat", referenceAssetIds:["two", "one"]}));
  await vi.waitFor(() => expect(root.textContent).toContain("Submitted · Success — Preparing character wardrobe…"));
  section = renderCharactersStage(intent => { void desk.handleCharacterIntent(intent); }).querySelector<HTMLElement>("[data-wardrobe-character]")!;
  [...section.querySelectorAll("button")].find(b => b.textContent === "Attach wardrobe image")!.click();
  await vi.waitFor(() => expect(host.invoke).toHaveBeenCalledWith("workflow_attach_character_wardrobe", {projectRoot:"/fixture/project", characterId:"alice", sourcePath:"/outside/coat.png"}));
});
