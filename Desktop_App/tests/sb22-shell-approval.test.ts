import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, expect, it, vi } from 'vitest';
import * as desk from '../src/workflowDesk';
import { getSurfaceHost } from '../src/studio/surfaces/session';
vi.mock('../src/settingsPanel',()=>({bindSettingsHost:vi.fn(),getSettings:()=>({selectedChatModel:null}),loadAppSettings:vi.fn(),populateChatModelSelect:vi.fn(),persistSettings:vi.fn(),renderSettingsPanel:vi.fn(),setSelectedChatModelFromSelect:vi.fn(),settingsAreDirty:()=>false}));
vi.mock('../src/voicePanel',()=>({bindVoiceHost:vi.fn(),openVoicePanelContext:vi.fn(),renderVoicePanel:vi.fn()}));
afterEach(()=>{desk.clearWorkflowDesk();vi.useRealTimers();vi.restoreAllMocks();document.body.replaceChildren();});
it('real shell keeps chat closed, Finish and saved chat bytes while exact modal routes separate paid event back to Studio',async()=>{
  vi.useFakeTimers();
  document.body.innerHTML=readFileSync('index.html','utf8').match(/<body>([\s\S]*)<\/body>/)![1];
  const fixture=JSON.parse(readFileSync('tests/fixtures/sb10-native-resume.json','utf8')).initial;
  const calls:{cmd:string;args:any}[]=[];let paid!:(payload:unknown)=>void;let acceptPaid=false;
  const history='# Saved Director chat\n\nUser: Preserve exact history.\n';
  const savedChat=join(mkdtempSync(join(process.env.TMPDIR!, 'sb22-history-')),'saved-chat.md');
  writeFileSync(savedChat,history);
  const savedJobs=JSON.stringify(fixture.state.jobs);
  const invoke=async(cmd:string,args:any)=>{
    calls.push({cmd,args:structuredClone(args)});
    if(cmd==='list_dir')return [];
    if(cmd==='workflow_import')return structuredClone(fixture);
    if(cmd==='workflow_prepare_assemble')return {...structuredClone(fixture),pendingAction:'Exact local fixture [[workbench_approve:SHELL1]]'};
    if(cmd==='director_approve')return {reply:'Waiting for exact media permission',toolEvents:['approve:awaiting-spend-authorization']};
    if(cmd==='confirm_unbounded_spend')return 'SHELLTOKEN';
    if(cmd==='media_generate_confirmed')return {mediaResult:'saved:null',continuation:null};
    throw Error('Forbidden '+cmd);
  };
  const asks:unknown[]=[];
  Object.assign(window,{workbench:{onCloseRequested:()=>()=>{},invoke,openProject:async()=>'/disposable/sb22-shell',ask:async(message:string,options:unknown)=>{asks.push({message,options});return acceptPaid;},rememberRecentProject:async()=>{},onMenu:()=>()=>{},onDirectorProgress:()=>()=>{},onSpendConfirmationRequired:(cb:typeof paid)=>{paid=cb;return()=>{};}}});
  await import('../src/main');const flush=()=>vi.advanceTimersByTimeAsync(160);await flush();
  document.querySelector<HTMLButtonElement>('#home-open-project')!.click();await flush();
  const chatClosed=()=>document.querySelector('#chat-panel')!.classList.contains('collapsed');
  if(!chatClosed())document.querySelector<HTMLButtonElement>('#toggle-chat-btn')!.click();
  expect(chatClosed()).toBe(true);
  // Read the real shell presentation class rather than checking callback prose.
  const shell=()=>document.querySelector('#chat-panel');
  const beforeClasses=[...document.querySelectorAll('[class*=collapsed]')].map(e=>e.className);
  await getSurfaceHost().run('Assemble shell fixture','workflow_prepare_assemble',{sceneId:1});await flush();
  expect(document.querySelector('dialog[data-operation-approval]')).not.toBeNull();
  expect([...document.querySelectorAll('[class*=collapsed]')].map(e=>e.className)).toEqual(beforeClasses);
  [...document.querySelectorAll<HTMLButtonElement>('dialog button')].find(b=>b.textContent==='Approve exact operation')!.click();await flush();
  expect(asks).toHaveLength(0);const owner=calls.find(c=>c.cmd==='director_approve')!.args.progressId;
  const payload={projectRoot:'/disposable/sb22-shell',provider:'fake',category:'media',operation:'atlas_generate_video',model:'fake-video',ownerRequestId:owner,workflowContinuationBound:true,args:{model:'fake-video',save_path:'/disposable/sb22-shell/output.mp4'},quote:{currency:'USD',requestHash:'b'.repeat(64),ledgerRevision:'fixture',disclosure:'unknown'}};
  acceptPaid=true;paid(payload);await flush();
  expect(asks).toEqual([{message:expect.stringContaining('fake-video'),options:{title:'Confirm paid generation',kind:'warning'}}]);
  expect(calls.filter(c=>c.cmd==='media_generate_confirmed')).toEqual([{cmd:'media_generate_confirmed',args:{projectRoot:payload.projectRoot,operation:payload.operation,mediaArgs:payload.args,token:'SHELLTOKEN'}}]);
  expect([...document.querySelectorAll('[class*=collapsed]')].map(e=>e.className)).toEqual(beforeClasses);
  expect(document.querySelector('#chat-messages')?.textContent).not.toContain('Exact local fixture');
  expect(readFileSync(savedChat,'utf8')).toBe(history);
  expect(JSON.stringify(fixture.state.jobs)).toBe(savedJobs);
  const afterApprovalClasses=[...document.querySelectorAll('[class*=collapsed]')].map(e=>e.className);
  const chatClosedDuringApproval=chatClosed();
  const finish=document.querySelector<HTMLButtonElement>('#inspector-tab-finish')!;
  expect(finish.disabled).toBe(false);finish.click();await flush();
  expect(finish.getAttribute('aria-selected')).toBe('true');
  expect(document.querySelector('#chat-panel')!.classList.contains('inspector-finish')).toBe(true);
  if(process.env.SB22_SHELL_RECEIPT)writeFileSync(process.env.SB22_SHELL_RECEIPT,JSON.stringify({beforeClasses,afterApprovalClasses,chatClosedDuringApproval,calls,asks,finishReachable:finish.getAttribute('aria-selected')==='true',shellClass:shell()?.className,savedChat,fixtureTranscriptPreserved:readFileSync(savedChat,'utf8')===history,fixtureJobsPreserved:JSON.stringify(fixture.state.jobs)===savedJobs,providerCalls:0},null,2));
});
