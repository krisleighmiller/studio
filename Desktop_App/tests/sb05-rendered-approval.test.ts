import {readFileSync} from "node:fs";
import vm from "node:vm";
import ts from "typescript";
import {afterEach, expect, it, vi} from "vitest";
import {renderAssembleStage} from "../src/studio/surfaces/assembleStage";
import {bindSurfaceHost, resetSurfaceSession} from "../src/studio/surfaces/session";
import type {SurfaceHost} from "../src/studio/surfaces/host";
import type {ProjectState, SceneRecord} from "../src/workflowTypes";
const source=readFileSync("src/workflowDesk.ts","utf8");const ast=ts.createSourceFile("desk.ts",source,ts.ScriptTarget.Latest,true);
const handler=ast.statements.find(n=>ts.isFunctionDeclaration(n)&&n.name?.text==="handleAssembleIntent")!;
const compiled=ts.transpileModule(handler.getText(ast),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.None}}).outputText;
const receipt=JSON.parse(readFileSync("tests/fixtures/sb04-saved-copy.json","utf8"));
afterEach(()=>{resetSurfaceSession();document.body.replaceChildren();});
it("requires an explicit rendered review action and reflects the exact persisted job receipt independently of sketch approval",()=>{
 const scenes=receipt.saved_job.assembly_snapshot.map((shot: any,i:number)=>({id:i+1,stable_id:`scene_${i+1}`,cuts:[{id:{source_scene:i+1,cut:1},stable_id:shot.shot_id,selected_take:shot.take_id,takes:[{id:shot.take_id,path:shot.path}]}],...(i===1?{animatic:{approved:true,shots:[{id:"middle",cut_id:{source_scene:2,cut:1},duration_seconds:shot.duration_seconds,transition:shot.transition}]}}:{})})) as SceneRecord[];
 const scene=scenes[1];
 const state={scenes,jobs:[receipt.saved_job],profile:{}} as ProjectState;
 const runAction=vi.fn();const sandbox=vm.createContext({runAction});vm.runInContext(compiled,sandbox);
 bindSurfaceHost({state,busy:null,error:null,blockerNames:()=>[],reviewExportPath:()=>null,resolvePath:(p:string)=>p,mediaUrl:async(p:string)=>p} as unknown as SurfaceHost);
 const paint=()=>document.body.replaceChildren(renderAssembleStage(scene,i=>sandbox.handleAssembleIntent(scene,i)));
 const button=(text:string)=>[...document.querySelectorAll('button')].find(b=>b.textContent===text)!;
 paint();expect(button('Approve rendered rough cut')).toBeDefined();expect(runAction).not.toHaveBeenCalled();
 button('Approve rendered rough cut').click();
 expect(runAction).toHaveBeenCalledExactlyOnceWith('Saving rendered rough-cut review…','workflow_approve_rendered_sequence',{jobId:receipt.saved_job.id});
 state.rendered_review={job_id:receipt.saved_job.id};paint();
 expect(button('Rendered rough cut approved').disabled).toBe(true);
 expect(document.querySelector('[aria-label="Rendered rough-cut review"]')?.textContent).toContain('Approved rendered sequence');
 state.rendered_review=undefined;paint();expect(button('Approve rendered rough cut').disabled).toBe(false);
 state.rendered_review={job_id:'older-job'};paint();expect(button('Approve rendered rough cut').disabled).toBe(false);
});
