//! Exercise the real decode/probe interleaving, not a pre-settlement stale input.
//! This integration-test executable has one test; its PATH override is process-local.
#[cfg(unix)]
#[test]
fn rejects_inputs_changed_during_audio_qc_and_preserves_delivered_bytes() {
    use serde_json::json;
    use std::{env, fs, os::unix::fs::PermissionsExt, process::Command};
    use workbench_host::{
        director_actions::DirectorAction,
        session,
        workflow::{
            dialogue_audio, import,
            state::{JobStatus, ProjectState},
        },
    };
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().join("project");
    fs::create_dir_all(root.join("Characters/A")).unwrap();
    fs::write(root.join("Characters/A/voice.wav"), b"voice fixture").unwrap();
    let raw = "Scenes/Scene1/Cut2/dialogue_1.wav";
    let original = json!({"version":2,"scenes":[{"id":1,"title":"QC race","cuts":[{"id":{"source_scene":1,"cut":2},"stable_id":"shot_two","dialogue":[{"speaker":"A","text":"First approved line."},{"speaker":"A","text":"Second approved line."}]}]}],"assets":[{"id":"voice_a","path":"Characters/A/voice.wav","role":"voice_sample","status":"draft"}],"jobs":[{"id":"speech","kind":"dialogue_audio","status":"pending","input_asset_ids":["voice_a"],"scope":{"kind":"shot","id":"shot_two"},"output_path":raw}]});
    let action: DirectorAction = serde_json::from_value(json!({"action":"run_specialist","specialist":"dialogue_audio","inputs":{"scene_id":1,"cut":2,"shot_id":"shot_two","dialogue":original["scenes"][0]["cuts"][0]["dialogue"],"voice_asset_id":"voice_a","voice_clone":"Characters/A/voice.wav","output_path":raw}})).unwrap();
    import::persist_state(
        &root,
        &ProjectState::from_json(&original.to_string()).unwrap(),
    )
    .unwrap();
    session::open(root.to_str().unwrap()).unwrap();
    let target = dialogue_audio::validate(&root, &action).unwrap();
    fs::create_dir_all(target.parent().unwrap()).unwrap();
    assert!(Command::new("ffmpeg")
        .args([
            "-v",
            "error",
            "-f",
            "lavfi",
            "-i",
            "sine=frequency=731:duration=1",
            "-c:a",
            "pcm_s16le"
        ])
        .arg(&target)
        .status()
        .unwrap()
        .success());
    let bytes = fs::read(&target).unwrap();
    let ffmpeg = Command::new("sh")
        .args(["-c", "command -v ffmpeg"])
        .output()
        .unwrap();
    assert!(ffmpeg.status.success());
    let ffmpeg = String::from_utf8(ffmpeg.stdout).unwrap().trim().to_string();
    let bin = dir.path().join("bin");
    fs::create_dir(&bin).unwrap();
    let changed_path = dir.path().join("changed.json");
    let marker = dir.path().join("qc-entered");
    let state_path = root.join("Preproduction/workflow_state.json");
    // Paths are generated by tempfile; shell-quote even when TMPDIR contains apostrophes.
    let quote = |s: &str| format!("'{}'", s.replace('\'', "'\\''"));
    let wrapper = format!("#!/bin/sh\ncase \" $* \" in *' -xerror '*) cp -- {} {} || exit 91; touch {} ;; esac\nexec {} \"$@\"\n", quote(changed_path.to_str().unwrap()), quote(state_path.to_str().unwrap()), quote(marker.to_str().unwrap()), quote(&ffmpeg));
    fs::write(bin.join("ffmpeg"), wrapper).unwrap();
    fs::set_permissions(bin.join("ffmpeg"), fs::Permissions::from_mode(0o755)).unwrap();
    struct RestorePath(std::ffi::OsString);
    impl Drop for RestorePath {
        fn drop(&mut self) {
            env::set_var("PATH", &self.0);
        }
    }
    let saved_path = env::var_os("PATH").unwrap();
    let _restore = RestorePath(saved_path.clone());
    env::set_var(
        "PATH",
        env::join_paths(std::iter::once(bin).chain(env::split_paths(&saved_path))).unwrap(),
    );
    for change in ["dialogue", "identity", "voice", "reservation", "output"] {
        fs::write(&state_path, original.to_string()).unwrap();
        let mut changed = original.clone();
        match change {
            "dialogue" => {
                changed["scenes"][0]["cuts"][0]["dialogue"][1]["text"] =
                    json!("Changed during real QC")
            }
            "identity" => changed["scenes"][0]["cuts"][0]["stable_id"] = json!("other_shot"),
            "voice" => changed["assets"][0]["path"] = json!("Characters/A/other.wav"),
            "reservation" => changed["jobs"][0]["status"] = json!("cancelled"),
            "output" => {
                changed["jobs"][0]["output_path"] = json!("Scenes/Scene1/Cut2/dialogue_2.wav")
            }
            _ => unreachable!(),
        }
        fs::write(&changed_path, changed.to_string()).unwrap();
        let _ = fs::remove_file(&marker);
        assert!(
            dialogue_audio::settle(&root, &action, &target).is_err(),
            "{change}: accepted a stale settlement"
        );
        assert!(
            marker.exists(),
            "{change}: did not enter real external audio QC"
        );
        let saved = ProjectState::from_json(&fs::read_to_string(&state_path).unwrap()).unwrap();
        assert!(
            !saved.assets.iter().any(|a| a.path == raw),
            "{change}: stale Draft registered"
        );
        assert_ne!(
            saved.jobs[0].status,
            JobStatus::Completed,
            "{change}: stale parent completed"
        );
        assert_eq!(
            fs::read(&target).unwrap(),
            bytes,
            "{change}: delivered WAV changed"
        );
    }
    session::close();
}
